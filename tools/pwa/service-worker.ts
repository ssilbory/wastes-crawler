// Build step for playing offline (src/ui/pwa.ts registers the result). After Vite writes dist/, this
// lists every file it wrote and emits dist/sw.js, a service worker that caches them all on install.
// The cache name is a hash of the file list, so each new build replaces the cache, and the old
// one is dropped once the new worker takes over.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

export const SW_FILE = 'sw.js';

/** Every file under `dir`, as URL paths relative to it, sorted. */
export function listFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out.push(relative(dir, p).split(sep).join('/'));
    }
  };
  walk(dir);
  return out.sort();
}

/** A short hash of the files' names and contents: the cache's version. */
export function buildVersion(dir: string, files: readonly string[]): string {
  const h = createHash('sha256');
  for (const f of files)
    h.update(f)
      .update('\0')
      .update(readFileSync(join(dir, f)));
  return h.digest('hex').slice(0, 12);
}

/**
 * The service worker's source. Pages are fetched network-first, so an online player always gets
 * the newest build; everything else comes from the cache first. Offline, any page falls back to
 * the cached index.html (the game routes by hash, so there is only the one page).
 */
export function serviceWorkerSource(files: readonly string[], version: string): string {
  // Every browser that runs service workers reads WOFF2, so the older .woff fonts are left out.
  const kept = files.filter((f) => f !== SW_FILE && !f.endsWith('.woff'));
  const precache = ['./', ...kept.map((f) => `./${f}`)];
  return `// Generated by tools/pwa/service-worker.ts; do not edit.
const CACHE = 'wastes-crawler-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() =>
        caches
          .match('./index.html', { ignoreVary: true })
          .then((r) => r || caches.match('./', { ignoreVary: true })),
      ),
    );
    return;
  }
  // Module scripts are fetched with an Origin header the precache requests lacked; a server's
  // "Vary: Origin" must not turn that into a cache miss.
  event.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
}

/** The Vite plugin: writes sw.js into the finished build. */
export function serviceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'wastes-crawler-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = join(config.root, config.build.outDir);
    },
    closeBundle() {
      const files = listFiles(outDir).filter((f) => f !== SW_FILE);
      writeFileSync(join(outDir, SW_FILE), serviceWorkerSource(files, buildVersion(outDir, files)));
    },
  };
}
